const BOT_SESSION_SECRET_NAME = 'meeting_bot_google_session';
const BOT_SESSION_VERSION = 1;

type StoredGoogleBotSession = {
  version: 1;
  accountEmail: string;
  createdAt: string;
  cookies: Array<{
    name: string; value: string; domain: string; path?: string; expires?: number;
    httpOnly?: boolean; secure?: boolean; sameSite?: 'Strict' | 'Lax' | 'None';
  }>;
  origins: Array<{ origin: string; localStorage: Array<{ name: string; value: string }> }>;
};

function getMeetingBotEncryptionKey(): Buffer {
  const value = (process.env.MEETING_BOT_SESSION_ENCRYPTION_KEY || '').trim();
  if (!value) throw new Error('The trial-only MEETING_BOT_SESSION_ENCRYPTION_KEY is not configured for this deployment.');
  if (/^[0-9a-f]{64}$/i.test(value)) return Buffer.from(value, 'hex');
  return crypto.createHash('sha256').update(value, 'utf8').digest();
}

function encryptMeetingBotSession(session: StoredGoogleBotSession) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', getMeetingBotEncryptionKey(), iv);
  const encrypted = Buffer.concat([cipher.update(JSON.stringify(session), 'utf8'), cipher.final()]);
  return { ciphertext: encrypted.toString('base64'), iv: iv.toString('base64'), authTag: cipher.getAuthTag().toString('base64'), version: BOT_SESSION_VERSION };
}

function decryptMeetingBotSession(record: any): StoredGoogleBotSession {
  const payload = record?.encryptedSession;
  if (!payload?.ciphertext || !payload?.iv || !payload?.authTag || payload.version !== BOT_SESSION_VERSION) {
    throw new Error('The saved Google bot session is invalid. Upload a fresh session export.');
  }
  const decipher = crypto.createDecipheriv('aes-256-gcm', getMeetingBotEncryptionKey(), Buffer.from(payload.iv, 'base64'));
  decipher.setAuthTag(Buffer.from(payload.authTag, 'base64'));
  const plaintext = Buffer.concat([decipher.update(Buffer.from(payload.ciphertext, 'base64')), decipher.final()]).toString('utf8');
  const session = JSON.parse(plaintext);
  if (session?.version !== 1 || !Array.isArray(session.cookies)) throw new Error('The saved Google bot session format is not supported.');
  return session as StoredGoogleBotSession;
}

function normalizeGoogleBotSession(input: any): StoredGoogleBotSession {
  if (!input || input.version !== 1 || !Array.isArray(input.cookies) || !Array.isArray(input.origins)) {
    throw new Error('Session file format not recognized. Use the Meeting Bot Google Session Export generated by our local helper.');
  }
  const accountEmail = String(input.accountEmail || '').trim().toLowerCase();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(accountEmail)) throw new Error('The session export must contain the dedicated bot Google account email.');
  if (input.cookies.length < 4 || input.cookies.length > 250) throw new Error('The export must contain between 4 and 250 cookies.');
  const cookies: StoredGoogleBotSession['cookies'] = [];
  for (const raw of input.cookies) {
    const name = String(raw?.name || '');
    const value = String(raw?.value || '');
    const rawDomain = String(raw?.domain || '').toLowerCase().trim();
    const domain = rawDomain.replace(/^\./, '');
    if (!name || name.length > 256 || !value || value.length > 8192 || !(domain === 'google.com' || domain.endsWith('.google.com'))) continue;
    const sameSiteRaw = String(raw?.sameSite || '');
    const sameSite = sameSiteRaw === 'Strict' || sameSiteRaw === 'Lax' || sameSiteRaw === 'None' ? sameSiteRaw : undefined;
    // Preserve CDP's leading dot exactly: host-only Google cookies must remain host-only.
    cookies.push({ name, value, domain: rawDomain,
      path: typeof raw.path === 'string' && raw.path.startsWith('/') ? raw.path : '/',
      ...(Number.isFinite(Number(raw.expires)) && Number(raw.expires) > 0 ? { expires: Number(raw.expires) } : {}),
      httpOnly: raw.httpOnly === true, secure: raw.secure !== false, ...(sameSite ? { sameSite } : {}) });
  }
  if (cookies.length < 4) throw new Error('Not enough Google sign-in cookies were found. Sign in to the dedicated account in Chrome and export again.');
  const allowedOrigins = new Set(['https://accounts.google.com', 'https://meet.google.com', 'https://www.google.com']);
  const origins: StoredGoogleBotSession['origins'] = [];
  for (const raw of input.origins.slice(0, 3)) {
    const origin = String(raw?.origin || '');
    if (!allowedOrigins.has(origin) || !Array.isArray(raw.localStorage)) continue;
    const localStorage = raw.localStorage.filter((x: any) => x && typeof x.name === 'string' && typeof x.value === 'string')
      .slice(0, 100).map((x: any) => ({ name: x.name.slice(0, 256), value: x.value.slice(0, 16384) }));
    origins.push({ origin, localStorage });
  }
  return { version: 1, accountEmail, createdAt: new Date().toISOString(), cookies, origins };
}

async function getMeetingBotSessionRecord(ctx: TenantContext) {
  const ref = tenantRepo(ctx).secretDoc(BOT_SESSION_SECRET_NAME);
  const snap = await ref.get();
  return { ref, record: snap.exists ? snap.data() : null };
}

async function getMeetingBotSessionStatus(ctx: TenantContext) {
  const { record } = await getMeetingBotSessionRecord(ctx);
  return { configured: Boolean(record?.encryptedSession), accountEmail: record?.accountEmail || null,
    connectedAt: record?.connectedAt || null, cookieCount: Number(record?.cookieCount || 0) };
}

async function saveMeetingBotSession(ctx: TenantContext, input: any) {
  const session = normalizeGoogleBotSession(input);
  const encryptedSession = encryptMeetingBotSession(session);
  const { ref } = await getMeetingBotSessionRecord(ctx);
  const connectedAt = new Date().toISOString();
  await ref.set({ name: BOT_SESSION_SECRET_NAME, encryptedSession, accountEmail: session.accountEmail,
    cookieCount: session.cookies.length, originCount: session.origins.length, connectedAt, updatedAt: connectedAt, storage: 'aes-256-gcm' });
  return { configured: true, accountEmail: session.accountEmail, connectedAt, cookieCount: session.cookies.length };
}

async function deleteMeetingBotSession(ctx: TenantContext) {
  const { ref } = await getMeetingBotSessionRecord(ctx);
  await ref.delete().catch(() => {});
}

function sendJson(res: ServerResponse, status: number, payload: Record<string, any>) {
  res.statusCode = status;
  res.setHeader('Content-Type', 'application/json');
  res.setHeader('Cache-Control', 'no-store, max-age=0');
  res.end(JSON.stringify(payload));
}

function sleep(ms: number) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Runs before Meet's application scripts. It observes incoming WebRTC audio
 * tracks, mixes them through Web Audio, and records the mixed stream in-page.
 * No OS audio device, PulseAudio, microphone, or speaker loopback is required.
 */
function installRemoteAudioCapture() {
  const w: any = window;
  if (w.__remoteAudioCaptureInstalled) return;
  w.__remoteAudioCaptureInstalled = true;

  const NativePeerConnection = w.RTCPeerConnection || w.webkitRTCPeerConnection;
  if (!NativePeerConnection) return;

  const remoteTracks = new Map<string, MediaStreamTrack>();
  const connectedTrackIds = new Set<string>();
  let audioContext: AudioContext | null = null;
  let destination: MediaStreamAudioDestinationNode | null = null;
  let recorder: MediaRecorder | null = null;
  let chunks: Blob[] = [];
  let recordingStartedAt = 0;
  let activeMimeType = 'audio/webm';

  const connectTrack = (track: MediaStreamTrack) => {
    if (!track || track.kind !== 'audio') return;
    remoteTracks.set(track.id, track);
    if (!audioContext || !destination || connectedTrackIds.has(track.id) || track.readyState === 'ended') return;
    try {
      const source = audioContext.createMediaStreamSource(new MediaStream([track]));
      source.connect(destination);
      connectedTrackIds.add(track.id);
    } catch {
      // A track may end while the page is reconnecting. A later track event will be observed.
    }
  };

  const WrappedPeerConnection = new Proxy(NativePeerConnection, {
    construct(target, args, newTarget) {
      const peerConnection = Reflect.construct(target, args, newTarget);
      peerConnection.addEventListener('track', (event: RTCTrackEvent) => {
        if (event.track?.kind === 'audio') connectTrack(event.track);
        for (const stream of event.streams || []) {
          for (const track of stream.getAudioTracks()) connectTrack(track);
        }
      });
      return peerConnection;
    },
  });

  try {
    w.RTCPeerConnection = WrappedPeerConnection;
    if (w.webkitRTCPeerConnection) w.webkitRTCPeerConnection = WrappedPeerConnection;
  } catch {}

  w.__remoteAudioCapture = {
    installed: true,
    status: () => ({
      audioTrackCount: remoteTracks.size,
      connectedTrackCount: connectedTrackIds.size,
      recorderState: recorder?.state || 'not-started',
    }),
    start: async () => {
      if (recorder && recorder.state !== 'inactive') {
        throw new Error('Audio recording is already running.');
      }
      const AudioContextConstructor = w.AudioContext || w.webkitAudioContext;
      if (!AudioContextConstructor || !w.MediaRecorder) {
        throw new Error('This Chromium build does not support Web Audio recording APIs.');
      }
      audioContext = new AudioContextConstructor();
      destination = audioContext.createMediaStreamDestination();
      await audioContext.resume();

      for (const track of remoteTracks.values()) connectTrack(track);

      const mimeType = MediaRecorder.isTypeSupported('audio/webm;codecs=opus')
        ? 'audio/webm;codecs=opus'
        : MediaRecorder.isTypeSupported('audio/webm')
          ? 'audio/webm'
          : '';
      activeMimeType = mimeType || 'audio/webm';
      recorder = mimeType
        ? new MediaRecorder(destination.stream, { mimeType })
        : new MediaRecorder(destination.stream);
      chunks = [];
      recorder.addEventListener('dataavailable', (event: BlobEvent) => {
        if (event.data && event.data.size > 0) chunks.push(event.data);
      });
      recordingStartedAt = performance.now();
      recorder.start(1000);
      return {
        audioTrackCount: remoteTracks.size,
        connectedTrackCount: connectedTrackIds.size,
        mimeType: recorder.mimeType || activeMimeType,
      };
    },
    stop: async (): Promise<AudioCaptureResult> => {
      if (!recorder) throw new Error('Audio recording was not started.');
      if (recorder.state !== 'inactive') {
        await new Promise<void>((resolve) => {
          recorder!.addEventListener('stop', () => resolve(), { once: true });
          recorder!.stop();
        });
      }
      const mimeType = recorder.mimeType || activeMimeType;
      const blob = new Blob(chunks, { type: mimeType });
      const bytes = new Uint8Array(await blob.arrayBuffer());
      let binary = '';
      for (let offset = 0; offset < bytes.length; offset += 0x8000) {
        binary += String.fromCharCode(...bytes.subarray(offset, offset + 0x8000));
      }
      const base64 = w.btoa(binary);
      const result = {
        base64,
        mimeType,
        byteLength: bytes.byteLength,
        recordingMs: Math.max(0, Math.round(performance.now() - recordingStartedAt)),
        audioTrackCount: remoteTracks.size,
      };
      try { await audioContext?.close(); } catch {}
      return result;
    },
  };
}

async function getMeetState(page: Page) {
  return page.evaluate(() => {
    const visibleText = (document.body?.innerText || '').replace(/\s+/g, ' ').trim();
    const bodyText = visibleText.toLowerCase();
    const labels = Array.from(document.querySelectorAll('button,[role="button"]'))
      .map((element) => [
        element.getAttribute('aria-label') || '',
        element.getAttribute('data-tooltip') || '',
        element.textContent || '',
      ].join(' ').replace(/\s+/g, ' ').trim().toLowerCase())
      .filter(Boolean);

    const hasJoinButton = labels.some((label) => /ask to join|join now/.test(label));
    const hasContinueWithoutMedia = labels.some((label) =>
      /continue without (?:a )?microphone and camera|continue without (?:microphone|camera)/.test(label)
    );
    const hasAllowMediaButton = labels.some((label) =>
      /allow microphone and camera|turn on microphone and camera/.test(label)
    );

    const joined = labels.some((label) => /leave call|hang up|end call/.test(label)) ||
      bodyText.includes("you're in the meeting") ||
      bodyText.includes('you are in the meeting');
    const waiting = bodyText.includes('asking to be let in') ||
      bodyText.includes("you'll join the call when someone lets you in") ||
      bodyText.includes('waiting for the host') ||
      bodyText.includes('waiting for someone to let you in') ||
      labels.some((label) => /ask to join/.test(label));
    const signInRequired = location.hostname === 'accounts.google.com' ||
      bodyText.includes('sign in to continue') ||
      bodyText.includes('you need to sign in') ||
      bodyText.includes('sign in with google') ||
      bodyText.includes('use your google account') ||
      bodyText.includes('sign in to join');
    const invalidCode = bodyText.includes('the meeting code you entered is invalid') ||
      bodyText.includes('meeting code is invalid') ||
      bodyText.includes('check that the code is correct');
    const meetingEnded = bodyText.includes('this meeting has ended') ||
      bodyText.includes('the meeting has ended');
    const explicitAccessDenied = bodyText.includes('you are not allowed to join') ||
      bodyText.includes('you do not have permission to join') ||
      bodyText.includes('you are not permitted to join');
    // Google currently includes generic security copy saying "You can't join this video call"
    // on the guest pre-join screen. Treat it as a denial only after the actionable
    // "Continue without microphone and camera" and "Ask to join / Join now" controls vanish.
    const genericAccessDeniedCopy = bodyText.includes("you can't join this video call");
    const accessDenied = explicitAccessDenied ||
      (genericAccessDeniedCopy && !hasContinueWithoutMedia && !hasJoinButton);
    const blocked = invalidCode || meetingEnded || accessDenied;
    const diagnosticLines = visibleText
      .split(/(?<=[.!?])\s+/)
      .filter((line) => /join|sign in|account|meeting|invalid|ended|host|permission|access|request|microphone|camera/i.test(line))
      .slice(0, 6)
      .join(' | ')
      .replace(/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi, '[email hidden]')
      .slice(0, 600);

    return {
      joined,
      waiting,
      signInRequired,
      blocked,
      blockedReason: invalidCode ? 'INVALID_MEETING_CODE'
        : meetingEnded ? 'MEETING_ALREADY_ENDED'
          : accessDenied ? 'MEET_ACCESS_RESTRICTED'
            : 'UNKNOWN_BLOCKED_SCREEN',
      hasJoinButton,
      hasContinueWithoutMedia,
      hasAllowMediaButton,
      pageTitle: document.title || '',
      pageUrl: location.href,
      diagnosticText: diagnosticLines || 'Google Meet loaded a page, but no recognizable join/status text was found.',
      visibleButtonLabels: labels.slice(0, 12),
    };
  });
}

async function clickContinueWithoutMedia(page: Page): Promise<boolean> {
  return page.evaluate(() => {
    const candidates = Array.from(document.querySelectorAll('button,[role="button"]'));
    const button = candidates.find((element) => {
      const label = [
        element.getAttribute('aria-label') || '',
        element.getAttribute('data-tooltip') || '',
        element.textContent || '',
      ].join(' ').replace(/\s+/g, ' ').trim().toLowerCase();
      const visible = Boolean((element as HTMLElement).offsetWidth || (element as HTMLElement).offsetHeight);
      return visible && /continue without (?:a )?microphone and camera|continue without (?:microphone|camera)/.test(label);
    }) as HTMLElement | undefined;
    if (!button) return false;
    button.click();
    return true;
  });
}

